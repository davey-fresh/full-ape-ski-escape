// FULL APE SKI ESCAPE v0.15 — Mama (knuckle-walk, wine, kids, lipstick)
function drawMama(ox,oy,scale,rage){
  const s=scale;
  const t=Date.now()/140;
  ctx.save();
  ctx.translate(ox,oy);
  ell(0,58*s,42*s,10*s,'rgba(0,0,0,0.28)');
  const legSwing=Math.sin(t)*8*s;
  ell(-14*s+legSwing, 38*s, 10*s, 14*s, '#8a3810');
  ell(-14*s+legSwing, 38*s, 7*s, 11*s, '#a04010');
  ell(16*s-legSwing, 40*s, 10*s, 14*s, '#8a3810');
  ell(16*s-legSwing, 40*s, 7*s, 11*s, '#a04010');
  ell(-16*s+legSwing, 50*s, 9*s, 5*s, '#6a2808');
  ell(18*s-legSwing, 52*s, 9*s, 5*s, '#6a2808');
  ell(0, 16*s, 36*s, 28*s, '#a04010');
  ell(0, 14*s, 30*s, 22*s, '#c05818');
  ell(0, 18*s, 20*s, 14*s, '#d87830');
  const armBob=Math.sin(t+1)*6*s;
  ell(-40*s, 8*s+armBob, 14*s, 18*s, '#a04010');
  ell(-40*s, 8*s+armBob, 10*s, 14*s, '#c05818');
  ell(-52*s, 28*s+armBob, 12*s, 10*s, '#8a3810');
  ell(-52*s, 28*s+armBob, 8*s, 7*s, '#a04010');
  ell(42*s, 4*s-armBob, 14*s, 16*s, '#a04010');
  ell(42*s, 4*s-armBob, 10*s, 12*s, '#c05818');
  ell(54*s, 18*s-armBob, 10*s, 9*s, '#8a3810');
  const gx=56*s, gy=8*s-armBob;
  ctx.fillStyle='#3a000c';
  ctx.beginPath();ctx.ellipse(gx, gy-10*s, 13*s, 11*s, 0, 0, Math.PI*2);ctx.fill();
  ctx.fillStyle='#8b0018';
  ctx.beginPath();ctx.ellipse(gx, gy-12*s, 10*s, 9*s, 0, 0, Math.PI*2);ctx.fill();
  ctx.fillStyle='#d01030';
  ctx.beginPath();ctx.ellipse(gx, gy-16*s, 8*s, 3.5*s, 0, 0, Math.PI*2);ctx.fill();
  ctx.strokeStyle='rgba(255,220,220,0.55)';ctx.lineWidth=2;
  ctx.beginPath();ctx.ellipse(gx, gy-16*s, 9*s, 4*s, 0, 0, Math.PI*2);ctx.stroke();
  px(gx-1.5*s, gy-2*s, 3*s, 12*s, '#f0e0e0');
  ell(gx, gy+10*s, 7*s, 2.5*s, '#f0e0e0');
  ell(0, -24*s, 28*s, 26*s, '#a04010');
  ell(0, -22*s, 22*s, 20*s, '#c05818');
  ell(0, -28*s, 14*s, 10*s, '#d87830');
  ell(-24*s, -28*s, 7*s, 8*s, '#8a3810');
  ell(24*s, -28*s, 7*s, 8*s, '#8a3810');
  ell(-10*s, -26*s, 7*s, 7*s, '#1a1008');
  ell(10*s, -26*s, 7*s, 7*s, '#1a1008');
  ell(-9*s, -25*s, 4*s, 4*s, '#f0e0c0');
  ell(11*s, -25*s, 4*s, 4*s, '#f0e0c0');
  ell(-8*s, -24*s, 2*s, 2*s, '#1a0800');
  ell(12*s, -24*s, 2*s, 2*s, '#1a0800');
  px(-16*s, -32*s, 12*s, 3*s, '#6a2808');
  px(4*s, -32*s, 12*s, 3*s, '#6a2808');
  ell(0, -10*s, 14*s, 8*s, '#6a2008');
  ell(0, -9*s, 12*s, 6*s, '#ff0040');
  ell(0, -9*s, 9*s, 4*s, '#ff2060');
  px(-8*s, -10*s, 16*s, 3*s, '#ff3080');
  px(-7*s, -10*s, 14*s, 3*s, '#f5f0e0');
  px(-6*s, -9*s, 3*s, 2*s, '#fff');
  px(-2*s, -9*s, 3*s, 2*s, '#fff');
  px(2*s, -9*s, 3*s, 2*s, '#fff');
  px(-8*s, -5*s, 16*s, 3*s, '#e00030');
  px(-6*s, -4*s, 12*s, 2*s, '#ff2060');
  ell(0, -16*s, 6*s, 4*s, '#c05818');
  px(-2*s, -16*s, 2*s, 2*s, '#3a1008');
  px(1*s, -16*s, 2*s, 2*s, '#3a1008');
  if(rage>0.4){ctx.globalAlpha=Math.min(0.22,rage*0.28);ctx.fillStyle='#ff4400';ctx.beginPath();ctx.arc(0,-6*s,56*s,0,Math.PI*2);ctx.fill();ctx.globalAlpha=1}
  ctx.restore();
  function drawKid(kx,ky,sc,phase){
    ctx.save();ctx.translate(kx,ky);
    const bob=Math.sin(phase)*4;
    const kGait=Math.sin(phase*1.5)*3;
    ell(0, 24*sc+bob, 12*sc, 4*sc, 'rgba(0,0,0,0.22)');
    ell(-8*sc+kGait, 14*sc+bob, 5*sc, 8*sc, '#8a3810');
    ell(8*sc-kGait, 14*sc+bob, 5*sc, 8*sc, '#8a3810');
    ell(0, 6*sc+bob, 12*sc, 11*sc, '#a04010');
    ell(0, 5*sc+bob, 9*sc, 8*sc, '#c05818');
    ell(0, -8*sc+bob, 10*sc, 9*sc, '#a04010');
    ell(0, -8*sc+bob, 7*sc, 7*sc, '#c05818');
    ell(-9*sc, -10*sc+bob, 3.5*sc, 4*sc, '#8a3810');
    ell(9*sc, -10*sc+bob, 3.5*sc, 4*sc, '#8a3810');
    ell(-3.5*sc, -9*sc+bob, 2*sc, 2*sc, '#1a1008');
    ell(3.5*sc, -9*sc+bob, 2*sc, 2*sc, '#1a1008');
    px(-3*sc, -3*sc+bob, 6*sc, 2*sc, '#c02040');
    ctx.restore();
  }
  drawKid(ox-42*s, oy+30*s, 0.52*s, t);
  drawKid(ox+46*s, oy+34*s, 0.48*s, t+1.7);
}
